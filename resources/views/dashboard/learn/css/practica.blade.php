<script>
    document.getElementById('quiz-revisar-btn').addEventListener('click', function () {
    const preguntas = document.querySelectorAll('.quiz-pregunta');
    let correctas = 0;
    let sinResponder = 0;

    preguntas.forEach(function (pregunta) {
        const correcta = pregunta.getAttribute('data-correcta');
        const nombreGrupo = pregunta.querySelector('input[type="radio"]').name;
        const seleccionado = pregunta.querySelector('input[name="' + nombreGrupo + '"]:checked');
        pregunta.classList.remove('border-green-500', 'border-red-500', 'bg-green-50', 'bg-red-50');

        if (!seleccionado) {
            sinResponder++;
            return;
        }

        if (seleccionado.value === correcta) {
            correctas++;
            pregunta.classList.add('border-green-500', 'bg-green-50');
        } else {
            pregunta.classList.add('border-red-500', 'bg-red-50');
        }
    });

    const total = preguntas.length;
    const resultadoDiv = document.getElementById('quiz-resultado');
    const resultadoTexto = document.getElementById('quiz-resultado-texto');

    let mensaje = '';
    if (sinResponder > 0) {
        mensaje = 'Te faltan ' + sinResponder + ' pregunta(s) por responder.';
        resultadoDiv.classList.remove('bg-lime-300', 'bg-red-300');
        resultadoDiv.classList.add('bg-yellow-300');
    } else if (correctas === total) {
        mensaje = '¡Perfecto! ' + correctas + '/' + total + ' — dominas los conceptos de CSS 🏆';
        resultadoDiv.classList.remove('bg-yellow-300', 'bg-red-300');
        resultadoDiv.classList.add('bg-lime-300');
        
        fetch('{{ route("completar.seccion") }}', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'X-CSRF-TOKEN': '{{ csrf_token() }}'
            },
            body: JSON.stringify({
                carpeta: '{{ $carpeta }}',
                seccion_id: '{{ $idActual }}'
            })
        })
        .then(response => {
            if (!response.ok) throw new Error('HTTP ' + response.status);
            return response.json();
        })
        .then(data => {
            if (data.message) {
                console.log('Progreso guardado');
            } else {
                console.warn('Error al guardar progreso:', data.error);
            }
        })
        .catch(error => {
            console.error('Error de conexión al guardar progreso:', error);
        });

    } else if (correctas >= total * 0.6) {
        mensaje = 'Bien hecho: ' + correctas + '/' + total + ' correctas. Repasa las que fallaste.';
        resultadoDiv.classList.remove('bg-yellow-300', 'bg-red-300');
        resultadoDiv.classList.add('bg-lime-300');
    } else {
        mensaje = 'Obtuviste ' + correctas + '/' + total + '. Repasa los módulos e inténtalo de nuevo.';
        resultadoDiv.classList.remove('bg-yellow-300', 'bg-lime-300');
        resultadoDiv.classList.add('bg-red-300');
    }

    resultadoTexto.textContent = mensaje;
    resultadoDiv.classList.remove('hidden');
    resultadoDiv.scrollIntoView({ behavior: 'smooth', block: 'center' });

    const quizContainer = document.getElementById('quiz-container');
    quizContainer.isComplete = function () {
        return window.__quizPerfecto === true;
    };
    window.__quizPerfecto = (correctas === total && sinResponder === 0);
});
</script>